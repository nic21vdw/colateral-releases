import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { githubReader, RELEASES_REPO, SOURCE_REPO } from './lib/github-read.mjs';
import { compareVersions } from './release-checksums.mjs';

export const START = '<!-- release-notes:start -->';
export const END = '<!-- release-notes:end -->';
const GENERIC = /^fixes landed by the nightly bug hunt\.?$/i;
const NOISE = [
  /^merge (pull request|branch)/i, /^revert\b/i, /^release colateral\b/i, /^(draft|wip)\b/i,
  /^(test|tests|ci|chore|docs|build|refactor|style)(\([^)]*\))?:/i, /\breport(s)?\b.*\b(nightly|loop|gauntlet)\b/i,
  /^(nightly|loop|gauntlet)\b.*\breport/i, /^bump\b/i, /\bAGENTS\.md\b/, /^(repair|fix|unblock) main\b/i, /\b(keep|make)\b.*\bgreen\b/i,
  /^prepare colateral\b/i, /\bregression tests?\b/i,
];

export function parseManifestNotes(notes) {
  const sections = new Map();
  let current = null;
  for (const raw of String(notes || '').split('\n')) {
    const line = raw.trim().replace(/^-\s+/, '');
    const head = /^CoLateral (\d+\.\d+\.\d+) - (.+)$/.exec(line);
    if (head) {
      current = { title: head[2].trim(), bullets: [] };
      sections.set(head[1], current);
    } else if (current && line) current.bullets.push(line);
  }
  return sections;
}

export function plainTitle(message) {
  const first = String(message || '').split('\n')[0].trim();
  if (NOISE.some(pattern => pattern.test(first))) return null;
  const cleaned = first.replace(/\s*\(#\d+\)\s*$/, '').replace(/^(feat|fix|perf)(\([^)]*\))?:\s*/i, '').trim();
  if (cleaned.length < 12) return null;
  return cleaned[0].toUpperCase() + cleaned.slice(1);
}

export function highlightsFromCommits(messages, limit = 8) {
  const seen = new Set();
  const picked = [];
  for (const message of messages) {
    const title = plainTitle(message);
    if (!title || seen.has(title.toLowerCase())) continue;
    seen.add(title.toLowerCase());
    picked.push(title);
  }
  return { highlights: picked.slice(0, limit), total: picked.length };
}

export function buildEntries({ versions, releases, sourceTags, notes, commitsFor }) {
  const releaseByTag = new Map(releases.map(release => [release.tag_name, release]));
  const tagged = versions.filter(version => sourceTags.has(`v${version}`));
  return Promise.all(versions.map(async version => {
    const release = releaseByTag.get(`v${version}`);
    const status = !release ? 'tag only' : release.draft ? 'draft, not published' : release.prerelease ? 'preview' : 'published';
    const date = (release?.published_at || release?.created_at || '').slice(0, 10) || null;
    const section = notes.get(version);
    const userBullets = (section?.bullets || []).filter(bullet => !GENERIC.test(bullet));
    let bullets = userBullets;
    let source = 'release notes';
    let more = 0;
    if (!bullets.length && sourceTags.has(`v${version}`)) {
      const previous = tagged.filter(other => compareVersions(other, version) < 0).at(-1);
      if (previous) {
        const { highlights, total } = highlightsFromCommits(await commitsFor(`v${previous}`, `v${version}`));
        bullets = highlights;
        more = total - highlights.length;
        source = `CoLateral-AI changes since ${previous}`;
      }
    }
    if (!bullets.length) source = 'no notes recorded';
    return { version, status, date, title: section?.title ?? null, bullets, more, source };
  }));
}

export function renderIndex(entries) {
  const lines = [START, '## Release notes', '',
    'Generated by `node scripts/release-notes-index.mjs` from release tags, the published update notes and CoLateral-AI change titles. Do not edit by hand.', ''];
  for (const entry of [...entries].sort((a, b) => compareVersions(b.version, a.version))) {
    lines.push(`### ${entry.version}${entry.title ? ` - ${entry.title}` : ''}`, '');
    lines.push(`_${[entry.status, entry.date].filter(Boolean).join(', ')}. Source: ${entry.source}._`, '');
    for (const bullet of entry.bullets) lines.push(`- ${bullet}`);
    if (entry.more > 0) lines.push(`- Plus ${entry.more} more ${entry.more === 1 ? 'change' : 'changes'}.`);
    if (entry.bullets.length) lines.push('');
  }
  lines.push(END);
  return lines.join('\n');
}

export function spliceReadme(readme, block) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start >= 0 && end > start) return readme.slice(0, start) + block + readme.slice(end + END.length);
  return `${readme.trimEnd()}\n\n${block}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const from = process.argv.find(value => value.startsWith('--from='))?.slice(7) ?? '1.0.70';
  const github = githubReader();
  const releases = await github.pages(`/repos/${RELEASES_REPO}/releases`);
  const sourceTags = new Set((await github.pages(`/repos/${SOURCE_REPO}/tags`)).map(tag => tag.name));
  const releaseTags = new Set((await github.pages(`/repos/${RELEASES_REPO}/tags`)).map(tag => tag.name));
  const versions = [...new Set([...releases.map(r => r.tag_name), ...releaseTags, ...sourceTags])]
    .filter(tag => /^v\d+\.\d+\.\d+$/.test(tag)).map(tag => tag.slice(1))
    .filter(version => compareVersions(version, from) >= 0).sort(compareVersions);
  const newest = releases.filter(r => !r.draft && r.assets?.some(a => a.name === 'latest.json')).sort((a, b) => compareVersions(b.tag_name, a.tag_name))[0];
  const notes = newest ? parseManifestNotes(JSON.parse(await github.assetText(newest.assets.find(a => a.name === 'latest.json'))).notes) : new Map();
  const commitsFor = async (base, head) => (await github.pages(`/repos/${SOURCE_REPO}/compare/${base}...${head}`, { pick: data => data.commits, limit: 3000 }))
    .map(commit => commit.commit.message).reverse();
  const entries = await buildEntries({ versions, releases, sourceTags, notes, commitsFor });
  const readmePath = join(dirname(fileURLToPath(import.meta.url)), '..', 'README.md');
  writeFileSync(readmePath, spliceReadme(readFileSync(readmePath, 'utf8'), renderIndex(entries)));
  console.log(`Wrote release notes for ${entries.length} versions (${entries.map(e => e.version).join(', ')}) to README.md`);
}
